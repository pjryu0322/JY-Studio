/**
 * 요구사항 협의실에서 AI(기획자)에게 질문이 향했을 때 돌아가는 안내 문구.
 * 서버 LLM 없이도 요구사항 정리를 돕는 최소 동작을 제공합니다.
 */
export function nextFacilitatorReply(userText: string, turnIndex: number): string {
  const t = userText.trim();
  const n = Math.max(0, turnIndex);
  const blocks = [
    `말씀해 주신 내용을 기준으로, **누가 언제** 이 서비스를 쓰는지 한 문장으로 정리해 볼까요? (내부 운영 / 외부 고객 / 관리자 등)`,
    `**이번에 꼭 포함할 기능**과 **이번에는 하지 않을 것**을 각각 2~3개씩 나눠 적어 주시면, 범위 논의가 훨씬 수월해집니다.`,
    `로그인·권한(역할별 접근)이 필요한지, 아니면 단순 공개 도구인지 알려 주세요. 요구사항 확정 시 보안/운영 관점에서 중요합니다.`,
    `**비기능** 측면에서 우선순위가 높은 것은 무엇인가요? (예: 응답 속도, 가용성, 감사 로그, 데이터 보존 기간 등)`,
    `지금까지 대화에서 **아직 모호한 표현**이 있다면 짚어 주세요. 예: “빨리”, “편하게”, “AI가 다 해준다”처럼 측정이 어려운 문장은 구체화가 필요합니다.`,
    `**성공 기준**을 하나만 정한다면 무엇인가요? (예: 첫 주에 n명이 핵심 시나리오를 완료한다 등) 측정 가능한 형태면 더 좋습니다.`,
  ];
  const core = t.length > 0 ? `입력 요약: “${t.length > 160 ? `${t.slice(0, 160)}…` : t}”\n\n` : "";
  return `${core}${blocks[n % blocks.length]}`;
}
